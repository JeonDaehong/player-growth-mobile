/**
 * ── 문 열한 개의 그림 (10×10) ──
 *
 * 위 띠 여섯(`TopBar` 의 `GATES`)과 아래 띠 다섯(`BottomNav` 의 `TABS`).
 *
 * ## 왜 글자가 아니라 그림인가
 *
 * 글자로 뒀었다. 자리를 잡는 것이 그 작업의 내용이었고 자리는 글자로도
 * 잡히기 때문인데, 다 세워 놓고 보니 **띠가 아니라 표**로 보였다. 열한 칸에
 * 두 글자씩 적힌 화면은 게임이 아니라 목록이다.
 *
 * ## 왜 10×10 인가
 *
 * `ICONS` 는 8×8 이다. 저건 숫자 옆에 붙는 표시라 그 크기면 되는데, 이건
 * 손가락으로 누르는 단추의 얼굴이라 30px 쯤으로 커진다. 8칸을 4배로 늘리면
 * 한 획이 4px 이라 굵고 뭉툭하다 — 10칸이면 획을 2칸 쓰고도 안쪽에 무늬가
 * 들어갈 자리가 남는다.
 *
 * ## 다 다른 실루엣이어야 한다
 *
 * 열한 개가 한 화면에 같이 뜬다. 흑백 도트라 색으로는 못 가르므로, 눈을
 * 가늘게 떴을 때 **덩어리 모양**이 서로 달라야 한다. 그래서 트로피(잔) ·
 * 별 · 봉투(가로로 넓은 것) · 리본 상자 · 두루마리 · 톱니 · 투구 · 가방 ·
 * 성 · 깃발 · 격자로 갈랐다 — 같은 윤곽이 둘 없다.
 */

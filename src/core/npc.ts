/**
 * 이번 말 걸기에서 이스터에그가 나오는가.
 *
 * `streak` 은 **이번이 몇 번째인가** 다 (1부터). 열 번째마다 나오므로
 * 한 번 보고 나서 열 번을 더 걸면 또 볼 수 있다 — 한 번만 나오게 하면
 * 친구에게 보여 주려다 못 보여 준다.
 */
export const isMaidSecret = (streak: number) =>
  streak > 0 && streak % MAID_SECRET_AT === 0;

/**
 * 다음 반응.
 *
 * 엘프 대사와 같은 규칙 — **직전 것은 다시 안 고른다.** 열 개나 되어도 순수
 * 무작위면 연달아 같은 말이 나오고, 그 한 번이 "몇 개 없구나" 로 읽힌다.
 */
export function nextIndex(prev: number, roll: number, n: number): number {
  if (n <= 1) return 0;
  if (prev < 0 || prev >= n) return Math.min(n - 1, Math.floor(roll * n));
  const pick = Math.min(n - 2, Math.floor(roll * (n - 1)));
  return pick >= prev ? pick + 1 : pick;
}

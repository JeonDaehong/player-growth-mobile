/**
 * 다음 대사.
 *
 * **방금 한 말은 안 고른다.** 순수 랜덤이면 열 줄이어도 같은 말이 연달아 두 번
 * 나오는 일이 흔하고, 그 한 번이 "대사가 몇 개 없구나" 로 읽힌다.
 *
 * @param prev 직전에 보여 준 줄의 번호. 없으면 -1
 * @param roll 0~1 난수 (테스트에서 고정해 넣는다)
 */
export function nextElfLine(prev: number, roll: number): number {
  const n = ELF_LINES.length;
  if (prev < 0 || prev >= n) return Math.min(n - 1, Math.floor(roll * n));
  // 직전 것을 뺀 n-1 개 중에서 고르고, 자리를 되돌린다
  const pick = Math.min(n - 2, Math.floor(roll * (n - 1)));
  return pick >= prev ? pick + 1 : pick;
}

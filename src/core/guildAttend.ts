/**
 * 길드 출석.
 *
 * 레이드는 체력을 쓰고 실력(아이템레벨)을 탄다. 그것만 있으면 템렙이 낮은 사람은
 * 길드에 들어와도 할 일이 없다. **출석은 누르기만 하면 되고 누구나 같은 값을 낸다** —
 * 하루 한 번, 길드 레벨만큼의 실버와 기여도, 그리고 길드 경험치를 남긴다.
 *
 * 보상이 **길드 레벨에 비례**하는 게 핵심이다. 길드가 자라면 출석 값이 같이 오르고,
 * 그 길드 레벨은 길드원들의 출석으로 오른다 — 사람이 모이는 이유가 하나 생긴다.
 */
import { s } from './currency';

/** 출석 한 번의 기여도 — 레이드 한 대(30)보다 낮게 둔다. 출석이 레이드를 대체하면 안 된다 */
export const ATTEND_GP = 15;

/** 출석한 길드원 한 명이 길드에 남기는 경험치 */
export const ATTEND_EXP_PER_MEMBER = 30;

/**
 * 출석 보상 — **현재 길드 레벨만큼의 실버**.
 *
 * Lv1 이면 1실버로 거의 없는 것이나 마찬가지고, Lv30 이면 30실버다.
 * 액수 자체는 작다. 이건 수입원이 아니라 "우리 길드가 몇 레벨인지" 를 매일
 * 손으로 확인시키는 장치다 — 숫자가 지난달보다 커져 있으면 그게 성장이다.
 */
export const attendReward = (guildLevel: number) => s(Math.max(1, guildLevel));

/**
 * 내 출석이 길드에 남기는 경험치 (나 + 오늘 출석한 길드원들).
 *
 * `mates` 는 **오늘 실제로 출석한 길드원 수**다. 예전엔 길드 인원에 지어낸
 * 성실도를 곱해 만들었는데, 그러면 아무도 안 들어와도 매일 사람이 찬 것처럼
 * 보였다. 지금은 같은 길드 프로필의 `guild_stats.attendDay` 를 센다
 * (state/useGuilds.ts) — 나 혼자면 정말로 1명이다.
 */
export function attendExp(mates: number): number {
  return (1 + Math.max(0, mates)) * ATTEND_EXP_PER_MEMBER;
}

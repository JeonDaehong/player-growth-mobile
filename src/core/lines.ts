/**
 * ── 영웅의 대사 ── 영웅 관리에서 말풍선에 뜬다 (`screens/home/HeroManage`).
 *
 * ## 왜 한 줄이 아니라 열 줄인가
 *
 * 한 사람당 한 마디만 있었다 (`CharDef.quote`). 그 한 줄이 수치와 기술 사이에
 * 늘 같은 자리에 떠 있었는데, **두 번째 볼 때부터는 글자가 아니라 무늬**였다.
 * 늘 같으니 읽을 이유가 없다.
 *
 * 열 줄이면 다르다. 볼 때마다 다른 말이 나오므로 눈이 한 번 더 간다. 그리고
 * 열 줄쯤 되면 한 마디로는 못 하던 일을 한다 — 이 사람이 **어떤 사람인지**가
 * 쌓인다. 이졸데는 물러서지 않는 사람이고 비앙카는 제 처지를 웃는 사람이라는
 * 것이, 설정 문서가 아니라 화면에서 읽힌다.
 *
 * ## 규칙 셋
 *
 *   1. **짧다.** 말풍선이 인물 머리 위 좁은 자리라 두 줄을 넘으면 안 된다.
 *      스물너덧 자가 상한이다
 *   2. **혼잣말이거나 곁의 누구에게 하는 말이다.** 플레이어를 부르지 않는다 —
 *      "주인님" 같은 말이 하나 끼면 그 순간 이 게임의 세계가 바뀐다
 *   3. **첫 줄은 `CharDef.quote` 다.** 여태 쓰던 그 한 마디를 여기 첫 자리에
 *      옮겨 두었으므로, 목록에 새로 적지 말고 저기서 읽어 온다 (`linesOf`)
 *
 * ## 쓰다듬기 대사는 따로다 (`PAT`)
 *
 * 머리를 쓰다듬으면 나오는 세 줄. 평소 대사와 **같은 목록에 섞지 않는다** —
 * 저건 가만히 있는 사람이 혼잣말하는 것이고 이건 **내가 한 일에 대한
 * 대답**이라, 섞이면 눌러도 안 눌러도 같은 말이 나오는 셈이 된다.
 *
 * 셋뿐인 것도 일부러다. 열 줄이면 그중 몇은 안 보고 지나치는데, 셋이면 세
 * 번만에 다 보고 "이 사람은 이런 반응을 하는구나" 가 닫힌다.
 *
 * ## 무엇을 만지나 — **머리다**
 *
 * 가슴을 만지면 반응하는 쪽으로 만들어 달라는 이야기가 있었고, 그건 안 만든다.
 * `docs/CHARACTER_ART_PROMPTS.md` 에 같은 판단이 이미 적혀 있다 — 싫다는
 * 반응을 눌러서 얻는 것을 게임 규칙으로 가르치는 꼴이 된다.
 *
 * 대상만 바꾸면 하고 싶던 것은 그대로 된다. 부끄러워하는 얼굴도, 특별한 대사
 * 셋도, 계속 누르고 싶어지는 것도. 머리를 쓰다듬는 쪽이 오히려 **넷의 성격이
 * 더 갈린다** — 이졸데는 갑옷은 뚫려도 이건 못 막고, 리안느는 화살을 쏘겠다고
 * 하고, 아녜스는 기도를 잊어버린다.
 *
 * 그림도 규칙도 아니고 글이라, 여기는 손으로 쓴다.
 */


/**
 * ── 영웅의 대사 ── 영웅 관리에서 말풍선에 뜬다 (`screens/home/HeroManage`).
 *
 * ## 왜 한 줄이 아니라 열 줄인가
 *
 * 한 사람당 한 마디만 있었다 (`CharDef.quote`). 그 한 줄이 수치와 기술 사이에
 * 늘 같은 자리에 떠 있었는데, **두 번째 볼 때부터는 글자가 아니라 무늬**였다.
 * 늘 같으니 읽을 이유가 없다.
 *
 * 열 줄이면 다르다. 볼 때마다 다른 말이 나오므로 눈이 한 번 더 간다. 그리고
 * 열 줄쯤 되면 한 마디로는 못 하던 일을 한다 — 이 사람이 **어떤 사람인지**가
 * 쌓인다. 이졸데는 물러서지 않는 사람이고 비앙카는 제 처지를 웃는 사람이라는
 * 것이, 설정 문서가 아니라 화면에서 읽힌다.
 *
 * ## 규칙 셋
 *
 *   1. **짧다.** 말풍선이 인물 머리 위 좁은 자리라 두 줄을 넘으면 안 된다.
 *      스물너덧 자가 상한이다
 *   2. **혼잣말이거나 곁의 누구에게 하는 말이다.** 플레이어를 부르지 않는다 —
 *      "주인님" 같은 말이 하나 끼면 그 순간 이 게임의 세계가 바뀐다
 *   3. **첫 줄은 `CharDef.quote` 다.** 여태 쓰던 그 한 마디를 여기 첫 자리에
 *      옮겨 두었으므로, 목록에 새로 적지 말고 저기서 읽어 온다 (`linesOf`)
 *
 * ## 만졌을 때 대사는 따로다 (`HEAD_LINES` · `CHEST_LINES`)
 *
 * 인물을 만지면 나오는 세 줄. 평소 대사와 **같은 목록에 섞지 않는다** —
 * 저건 가만히 있는 사람이 혼잣말하는 것이고 이건 **내가 한 일에 대한
 * 대답**이라, 섞이면 눌러도 안 눌러도 같은 말이 나오는 셈이 된다.
 *
 * 셋뿐인 것도 일부러다. 열 줄이면 그중 몇은 안 보고 지나치는데, 셋이면 세
 * 번만에 다 보고 "이 사람은 이런 반응을 하는구나" 가 닫힌다.
 *
 * ## 머리와 가슴이 **다른 목록**인 까닭
 *
 * 둘 다 부끄러워하지만 **부끄러운 종류가 다르다.** 머리를 쓰다듬는 것은
 * 애정이고, 그 앞에서 무너지는 것은 위엄이다 — 기사한테 이러지 말라거나,
 * 나 연상이라거나, 머리 헝클어진다거나. 가슴 쪽은 애정이 아니라 사고라,
 * 무너지는 것이 말 자체다 (말이 막히고 존댓말이 무너진다).
 *
 * 한 목록으로 합치면 머리를 쓰다듬었는데 "거긴 갑옷도 없다고" 가 나온다.
 * 그러면 **어디를 눌렀는지가 화면에 안 남는다** — 눌러 보고 알아내는 재미가
 * 그 자리에서 사라진다.
 *
 * ## 넷이 **다르게 부끄러워한다**
 *
 * 이게 이 여섯을 만드는 이유다. 넷이 다 "꺄악" 하면 세 줄씩 쓸 값이 없다.
 *
 *   이졸데  말을 못 잇는다 — 겁이 아니라 이런 걸 겪어 본 적이 없는 것
 *   비앙카  농담으로 덮으려다 제 얼굴이 빨개진 걸 먼저 들킨다
 *   리안느  말이 짧아진다. 세 글자면 끝난다
 *   아녜스  존댓말이 무너졌다 다시 붙는다
 *
 * ## **화내는 쪽이 아니다**
 *
 * 한 번 이 셋을 협박조로 써 놨었다 (`검을 뽑겠다` · `화살 쏜다` · `지금
 * 화났어`). 받아 주는 말이 되지 않게 하려던 것인데, 반대쪽으로 너무 가서
 * 넷이 다 **부끄러운 게 아니라 화난 사람**이 됐다.
 *
 * 노리는 자리는 그 사이다. 당황하고 얼굴이 붉어지되, 좋아하지도 위협하지도
 * 않는다 — 그래서 대사에 **위협이 안 들어간다**(뽑겠다 · 쏜다 · 화났다).
 * 대신 말이 막히고, 딴 데를 보고, 제 얼굴이 뜨겁다는 걸 저도 안다.
 *
 * 그림도 규칙도 아니고 글이라, 여기는 손으로 쓴다.
 */


/**
 * ── 숨겨진 반응 ── **열 번 연속으로** 눌렸을 때 (`HeroManage` 의 `RUN_NEED`).
 *
 * 같은 자리를 1초 안에 열 번 두들겨야 나온다. 손이 미끄러져서 나올 수 있는
 * 수가 아니고, 그래서 **찾아낸 사람만 보는 것**이 된다.
 *
 * 그림은 다리가 풀려 주저앉은 것이고 (`char_down`) 몸에서 김이 오른다.
 * 말도 거기 맞춘다.
 *
 * ## 넷 다 **하우우** 로 시작한다
 *
 * 위의 세 목록(평소 · 머리 · 가슴)은 넷이 다 다르게 말하는 것이 규칙이었다.
 * 여기서는 반대로 **넷이 같은 소리로 시작한다** — 이 칸은 성격이 무너진
 * 자리라, 성격이 남아 있으면 안 무너진 것이다. 말이 되기 전의 소리가 먼저
 * 나오고, 그다음에야 각자의 말투가 조금 돌아온다.
 *
 * ## 문장이 안 끝난다
 *
 * 넷 다 말줄임으로 끝난다. 위 목록들은 "말을 하려다 실패하는" 것이었지만
 * 이건 **말하기를 그만두는** 것이다. 끝맺으면 아직 여유가 있는 사람이 된다.
 */
const DOWN_LINES: Record<string, readonly string[]> = {
  /* 위엄이 통째로 사라졌다 — 그걸 본인이 제일 잘 안다 */
  knightgirl: [
    '하, 하우우…… 더는, 더는 못 하겠어……',
    '하우우…… 기사가, 기사가 이러면 안 되는데……',
    '하으으…… 아무한테도 말하지 마……',
  ],
  /* 웃음이 완전히 녹았다 */
  bunnyaxe: [
    '하우우…… 나 진짜 녹는다니까……',
    '하우우…… 이건 반칙이지, 이건……',
    '하으으…… 다리에 힘이, 힘이……',
  ],
  /* 말수가 적은 사람이 소리만 낸다 */
  elfarcher: [
    '하우우…… 그만…… 그만해……',
    '하으으…… 못 일어나겠어……',
    '하우우…… 아무 말도, 하지 마……',
  ],
  /* 존댓말이 끝까지 안 무너진다 — 그게 더 무너져 보인다 */
  nun: [
    '하으으…… 주, 주님…… 죄송해요……',
    '하우우…… 이러면, 이러면 안 되는데요……',
    '하으으…… 조금만…… 조금만 이대로……',
  ],
};

/**
 * 숨겨진 반응으로 할 말들. 규칙은 `headOf` 와 같다.
 */
export function downOf(id: string): readonly string[] {
  return DOWN_LINES[id] ?? [];
}

/**
 * 머리를 쓰다듬었을 때 할 말들. 없으면 빈 배열이고, 그때는 부르는 쪽이
 * **평소 대사로 넘긴다** — 눌렀는데 아무 일도 안 일어나는 것보다 낫다.
 */
export function headOf(id: string): readonly string[] {
  return HEAD_LINES[id] ?? [];
}

/** 가슴 쪽을 만졌을 때 할 말들. 규칙은 `headOf` 와 같다 */
export function chestOf(id: string): readonly string[] {
  return CHEST_LINES[id] ?? [];
}

/**
 * 이 사람이 할 수 있는 말 전부. **첫 줄은 `quote` 다.**
 *
 * `quote` 를 부르는 쪽에서 넘겨받는다. 여기서 `core/chars` 를 읽어 오면
 * 사람 표와 대사 표가 서로를 물게 되는데 (`tools/check-cycles`), 대사는
 * 사람 표에 딸린 것이지 사람 표가 대사에 딸린 것이 아니다.
 *
 * 아직 대사를 안 쓴 사람은 `quote` 한 줄만 돌려준다 — 빈 배열을 돌려주면
 * 부르는 쪽이 말풍선을 못 그린다.
 */
export function linesOf(id: string, quote?: string): readonly string[] {
  const more = MORE[id] ?? [];
  /* `quote` 가 비어 있는 사람도 있다 — 빈 줄이 말풍선에 뜨면 안 된다 */
  return quote ? [quote, ...more] : more;
}

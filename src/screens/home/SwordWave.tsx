/**
 * 날아가는 검기 — 스킬을 쓰면 아군 자리에서 생겨 오른쪽으로 지나간다.
 *
 * ## 검기든 화살이든 여기를 지난다
 *
 * 이름은 검기에서 왔지만 하는 일은 "몸을 떠나 **노린 놈에게 가는 것**" 이다.
 * 어느 그림을 쓸지는 캐릭터가 정한다 (`core/chars` 의 `projSet`) — 근접은
 * `<id>_wave`, 원거리는 `<id>_shot`.
 *
 * ## 한 장만 쓴다
 *
 * 시트에는 세 프레임이 있다 (생성 · 비행 · 소멸). 그런데 3번은 초승달이
 * 조각조각 흩어진 그림이라, 40px 로 줄여 화면을 가로지르면 **날아가는 물체가
 * 아니라 먼지**로 보인다.
 *
 * 그래서 `wave_1` 한 장만 쓰고, **이동과 흐려짐은 코드가 한다.** 프레임을
 * 넘기는 것보다 한 장을 잘 움직이는 쪽이 이 크기에서는 낫다.
 *
 * ## 노린 놈까지만 간다
 *
 * 날아갈 거리(`dist`)를 밖에서 받는다. 예전에는 몸 길이의 다섯 배를 무조건
 * 갔다 — 앞줄을 노렸는데도 지나쳐 화면 끝까지 갔고, 뒷줄을 노렸는데도 중간에
 * 흐려져 사라졌다. 어느 쪽이든 **때리는 놈과 날아가 닿는 곳이 달랐다.**
 *
 * 자리를 아는 것은 무대뿐이므로(`BattleView` 의 `spotOf`) 거기서 재서 넘긴다.
 *
 * ## 왜 몸에서 떼어냈나
 *
 * 검기는 캐릭터를 떠나 화면을 가로질러야 한다. 캐릭터 스프라이트 안에 같이
 * 그리면 몸에 묶여서 못 움직인다 — 그래서 §E 를 두 장으로 나눠 받았다.
 *
 * ## 그런데 그리기는 캐릭터 안에서 한다
 *
 * 처음엔 무대의 고정 좌표(`left: 40`)에서 생기게 했다. 그러면 캐릭터가 앞으로
 * 나가 있든 뒤에 있든 늘 같은 자리에서 나와서 **검과 따로 놀았다.**
 * `Fighter` 안에 두면 그 사람이 선 자리에서 자동으로 따라오고, 검끝 위치도
 * 스프라이트 크기에 비례해 잡을 수 있다.
 */
import React, { useEffect, useMemo, useRef, useState } from 'react';
import { Animated, Easing } from 'react-native';
import { isRangedChar, projFrame, projSet } from '@/core/chars';
import { Sprite } from '@/ui/Sprite';

/**
 * 날아가는 속도 (px/ms).
 *
 * 예전에는 **시간**이 고정이었다 (460ms). 거리도 고정이었으니 (몸 길이의
 * 다섯 배) 속도가 저절로 일정했다. 그런데 이제는 노린 놈이 어디 서 있느냐에
 * 따라 거리가 달라지므로, 시간을 붙박아 두면 앞줄을 노릴 때는 기어가고
 * 뒷줄을 노릴 때는 순간이동한다. **고정할 것은 속도 쪽이다.**
 */
/*
  0.62 로 시작했다가 **두 배로 올렸다.**

  거리를 재서 시간을 뽑는 식은 맞았는데 속도를 너무 얌전하게 잡았다. 화살이
  200px 을 320ms 에 걸쳐 가니, 쏘는 동작은 끝났는데 화살은 아직 반도 못 간
  상태가 눈에 띄었다 — 활에서 나간 것이 아니라 떠밀려 가는 것으로 보인다.

  화살은 원래 눈으로 좇기 어려운 물건이다. 보이기는 해야 하므로 아래 하한이
  있고, 그 위로는 빠를수록 "쐈다" 에 가깝다.
*/
const WAVE_SPEED = 1.24;

/** 아무리 가까워도 이만큼은 날아간다 — 안 그러면 나오자마자 사라진다 */
const WAVE_MIN_MS = 80;
/** 아무리 멀어도 이 안에는 닿는다 — 다음 공격과 겹치면 안 된다 */
const WAVE_MAX_MS = 260;

/**
 * 그 거리를 날아가는 데 걸리는 시간 (ms).
 *
 * **피해도 이 시간 뒤에 들어간다.** 그림이 적에게 닿는 순간과 체력이 닳는
 * 순간이 같아야 한다 — 화살이 아직 활 옆에 있는데 저 끝의 적이 죽으면
 * 날아가는 게 무슨 소용인지 알 수 없다.
 */
export function flyMsOf(dist: number): number {
  return Math.round(
    Math.min(WAVE_MAX_MS, Math.max(WAVE_MIN_MS, Math.abs(dist) / WAVE_SPEED)),
  );
}


/**
 * 검끝이 스프라이트 안 어디쯤인가.
 *
 * `sk_2`(베는 칸) 를 실제로 재 보니 **오른쪽 끝, 위에서 33% 지점**이었다.
 * 눈대중으로 잡지 않고 픽셀을 세서 넣는다 — 캐릭터마다 검 길이가 다르면
 * 여기가 어긋나고, 그러면 검기가 허공에서 튀어나온다.
 */
const TIP_X = 0.98;
const TIP_Y = 0.33;

export function SwordWave({
  charId, nonce, size, dist, proj, mul,
}: {
  charId: string;
  /** 이 기술이 지목한 투사체 시트 — 없으면 그 사람의 기본 것 (`SkillDef.proj`) */
  proj?: string;
  /** 몸 길이의 몇 배로 그릴까 (`SkillDef.projMul`) */
  mul?: number;
  nonce: number;
  size: number;
  /**
   * 노린 대상까지의 거리(px).
   *
   * 예전에는 몸 길이의 다섯 배를 무조건 날아갔다. 그러면 앞줄을 노렸는데도
   * 화면 끝까지 지나가고, 뒷줄을 노렸는데도 중간에서 사라진다 — 어디를
   * 때리는지가 그림과 안 맞는다.
   */
  dist: number;
}) {
  const ranged = isRangedChar(charId);
  const t = useRef(new Animated.Value(0)).current;
  const [on, setOn] = useState(false);
  /* 캐릭터가 서 있는 내내 사는 값이다 — 날릴 때마다 가지를 새로 달면 안 된다 */
  /*
    **닿을 때까지 안 흐려진다.**

    예전에는 0.45 지점에서 벌써 0.7 까지 내려갔다. 거리가 고정일 때는 그게
    "기운이 번지며 스러진다" 로 읽혔지만, 지금은 끝점이 곧 적이 선 자리다 —
    가는 도중에 옅어지면 **적에게 닿기 전에 사라진 것**으로 보인다.

    0.82 까지 제 색으로 가다가 마지막 한 뼘에서 꺼진다. 그 한 뼘이 적의 몸에
    겹치는 구간이라, 거기서 꺼지는 것이 "박혔다" 로 읽힌다.
  */
  const fade = useMemo(() => t.interpolate({
    inputRange: [0, 0.82, 1], outputRange: [1, 1, 0],
  }), [t]);
  /*
    **검기만 커진다.**

    베어 낸 기운은 퍼져 나가므로 커지면서 옅어지는 게 맞다. 그런데 화살은
    물체다 — 날아가면서 두 배로 부풀면 화살이 아니라 다른 것이 된다.
  */
  const grow = useMemo(() => t.interpolate({
    inputRange: [0, 1], outputRange: ranged ? [1, 1] : [1.05, 2.0],
  }), [t, ranged]);
  const fly = useMemo(() => t.interpolate({
    inputRange: [0, 1], outputRange: [0, dist],
  }), [t, dist]);

  useEffect(() => {
    if (nonce <= 0) return;
    setOn(true);
    t.setValue(0);
    const ms = flyMsOf(dist);
    const a = Animated.timing(t, {
      toValue: 1,
      duration: ms,
      /*
        **일정한 속도로 간다.**

        예전에는 `Easing.out(cubic)` 이었다 — 튀어나가 늦추는 곡선이라, 거리가
        고정일 때는 "베면서 날렸다" 를 만들었다. 그런데 끝점이 적이 선 자리인
        지금은 그 곡선이 **적 앞에서 거의 멎어 미끄러져 들어가는 것**으로
        보인다. 날아가는 물체는 등속이 맞다.
      */
      easing: Easing.linear,
      useNativeDriver: true,
    });
    a.start();
    const end = setTimeout(() => setOn(false), ms);
    /* 날아가는 중에 화면에서 빠질 수 있다 — 타이머만 치우면 값은 계속 돈다 */
    return () => { clearTimeout(end); a.stop(); };
  }, [nonce, t, dist]);

  if (!on) return null;
  /*
    ── 아주 큰 것은 **무대가 직접 그린다** ── (`PierceAura` 의 `GiantArrow`)

    여기는 인물 안이라 두 가지가 몸에 묶인다: 나가는 높이가 검끝이고
    (`TIP_Y`), 가는 거리가 노린 놈까지다. 손가락만 한 화살에는 그게 맞지만,
    몸의 세 배짜리 거대 화살은 그 규칙 아래에서 **어깨 높이로 나가 제일
    가까운 놈 앞에서 멎었다** — 길에 선 것을 전부 꿴다는 기술인데 화면에서는
    줄의 앞부분만 지나갔다.

    크기를 문턱으로 쓴다 (`SkillDef.projMul`). 꿰뚫는 기운을 켜는 조건과
    **같은 값**이라 (`BattleView` 의 `onSkill`), 둘이 갈라져 화살은 몸에서
    나가는데 고리만 무대에서 퍼지는 일이 안 생긴다.
  */
  if ((mul ?? 1) >= 2) return null;

  return (
    <Animated.View
      pointerEvents="none"
      style={{
        position: 'absolute',
        /* 검끝에서 출발한다 */
        left: size * TIP_X,
        top: size * TIP_Y - size * 0.25,
        zIndex: 20,
        /*
          날아가면서 **커지고 흐려진다.**

          멀어지는 물체는 작아지는 게 맞지만, 이건 멀어지는 게 아니라 힘이
          퍼져 나가는 것이다. 커지면서 옅어져야 "베어 낸 기운이 번진다" 로
          읽힌다 — 작아지면 그냥 날아가 사라지는 돌멩이다.
        */
        opacity: fade,
        transform: [
          { translateX: fly },
          /*
            **처음부터 제 크기로 나간다.**

            0.65 배로 시작했더니 나오는 순간에는 칼에 겹쳐 안 보이고, 커져서
            눈에 띌 때쯤엔 이미 베기가 끝나 있었다 — 그래서 늦게 나가는 것처럼
            보였다. 나가는 시점은 맞았고 크기가 문제였다.
          */
          { scale: grow },
        ],
      }}
    >
      {/*
        좌우를 뒤집는다.

        시트의 초승달은 **오목한 쪽이 오른쪽**을 보고 있다. 그대로 두면 오른쪽으로
        날아갈 때 파인 쪽이 앞장서서, 베고 나가는 게 아니라 뒤로 끌려가는 것처럼
        보인다. 뒤집으면 볼록한 날이 앞을 향한다.
      */}
      {/*
        **검기만 뒤집는다.**

        검기 시트는 초승달이 왼쪽으로 볼록하게 그려져 나왔다. 오른쪽으로
        날아가려면 볼록한 쪽이 앞서야 하므로 뒤집어야 한다. 화살은 촉이
        이미 오른쪽을 보고 있어서 뒤집으면 거꾸로 날아간다.
        (한동안 둘 다 뒤집고 있었고, 그래서 화살이 뒤로 날았다.)

        에셋을 고치지 않고 여기서 뒤집는 이유는 **눈으로 확인하며 고치기
        위해서**다. 그림을 다시 자르면 번들러가 옛 그림을 물고 있어 화면이
        안 바뀌는 일이 생긴다. 이 줄은 고치는 즉시 반영된다.
      */}
      <Sprite
        /*
          기술이 제 시트를 지목하면 그것을, 아니면 그 사람의 기본 투사체를
          쓴다 (`SkillDef.proj`). 리안느의 거대 화살 하나가 지목한다 —
          평소 화살로 그리면 길에 선 적을 모두 꿰는 것이 손가락만 하게
          지나간다.

          아직 그 시트가 없으면 기본 화살로 떨어진다 (`fallbackSet`).
        */
        set={proj || projSet(charId)}
        name={projFrame(charId)}
        /*
          기술이 크기를 지목하면 그것을 쓴다 (`SkillDef.projMul`).

          제 시트를 가진 것은 1.25, 기본 화살·검기는 0.85 다. 궁극기 하나가
          3 을 부른다 — 거대 화살은 크기 자체가 기술의 절반이다.
        */
        size={size * (mul ?? (proj ? 1.25 : 0.85))}
        fallbackSet={projSet(charId)}
        flip={!ranged}
      />
    </Animated.View>
  );
}

/**
 * 바닥 — 던파식 쿼터뷰 평면.
 *
 * ## 왜 선 하나로는 안 되나
 *
 * 처음엔 바닥이 **가로선 한 줄**이었다. 완전한 정측면(2D 횡스크롤)이면 그게
 * 맞는데, 쓰고 있는 스프라이트(`duel/`, `cr_*`)는 정측면이 아니라 **살짝 위에서
 * 내려다본 각도**다. 발도 몸통보다 앞으로 나와 있다.
 *
 * 선 한 줄 위에 그 그림을 세우면 인물은 비스듬한데 바닥만 정면이라 둘이
 * 서로 다른 세계에 있는 것처럼 보인다. 바닥이 **면**이어야 한다.
 *
 * ## 어떻게 면으로 보이게 하나
 *
 * 세 가지가 겹쳐야 평면으로 읽힌다. 셋 다 **앞이 크고 뒤가 작다.**
 *
 *   1. **폭** — 앞이 넓고 뒤(위)가 좁다. 소실점이 위에 있다는 뜻이다
 *   2. **간격** — 뒤로 갈수록 촘촘해진다. 등간격이면 그냥 줄무늬다
 *   3. **또렷함** — 앞이 진하고 뒤가 흐리다
 *
 * 처음 만들 때 셋 다 **거꾸로** 넣었다 (앞이 좁고, 앞이 촘촘하고, 앞이 흐리게).
 * 그러면 바닥이 위로 벌어지는 깔때기가 되어 평면감이 아예 안 산다.
 * 세 값 모두 `t=0` 이 **앞(아래)** 이라는 걸 기준으로 잡는다.
 *
 * ## 1-bit 라서
 *
 * 그라디언트를 못 쓴다. 대신 **선의 개수와 투명도**로 거리를 만든다.
 * 던파처럼 바닥 텍스처를 깔 수도 있지만, 이 게임은 인물도 흑백 도트라
 * 바닥까지 무늬가 들어가면 인물이 묻힌다 — 선만 남기는 쪽이 맞다.
 */
import React from 'react';
import { View } from 'react-native';

/** 바닥판의 세로 두께 — 무대 아래쪽 이만큼이 "땅" 이다 */
/**
 * 무대 확대 배율.
 *
 * 처음 잡은 치수(무대 138px · 인물 54px)는 폰 화면을 기준으로 한 것이었다.
 * 그런데 이 화면이 게임의 전부라, 그 크기로는 무엇이 벌어지는지 잘 안 보인다 —
 * 특히 한 줄에 넷이 겹쳐 서는 지금은 더 그렇다.
 *
 * **여기 하나만 고치면 무대 전체가 같이 커진다.** 아래 치수들이 전부 이 값에
 * 걸려 있고, 대형 계산(`closeInFor`·`squeezeFor`)도 그 치수에서 나오므로
 * 배율을 바꿔도 겹치거나 잘리지 않는다.
 */
export const ZOOM = 1.4;

const px = (n: number) => Math.round(n * ZOOM);

/**
 * 바닥판 높이 — **땅으로 쓰는 띠.**
 *
 * 46 이었다. "땅 면적을 넓혀서 캐릭터들이 좀 분산되어 보이게" 라는 말을 듣고
 * 68 로 올렸다. 이 값이 곧 **뒷줄이 물러날 수 있는 깊이**다 — 네 자리가
 * `DEPTH_LIFT` 씩 물러나는데, 띠가 얕으면 그 넷이 한 줄에 붙어 선다.
 */
export const GROUND_H = px(68);

/**
 * 무대 높이.
 *
 * 138 이었다. "인 게임 화면 위에를 좀 길게" — 위쪽이 늘어난 만큼 배경의
 * 하늘이 보이고, 머리 위로 뜨는 것들(피해 숫자 · 말풍선 · 하늘에서 내려오는
 * 벼락)이 잘릴 걱정이 줄어든다.
 *
 * 180 이 상한이다. 폰 세로 화면에서 위 띠(두 줄) · 상자 줄 · 세 줄 · 파티 ·
 * 아래 띠를 다 세우고 남는 자리가 그쯤이다. 더 키우면 파티를 보려고 스크롤을
 * 내려야 하고, 그러면 "둘이 같이 보인다" 가 깨진다.
 */
export const STAGE_H = px(180);

/** 아군 한 명이 차지하는 폭 (맨 앞 기준) */
export const PARTY_W = px(54);

/** 잡몹 한 마리 */
export const FOE_W = px(52);

/**
 * 우두머리 — 잡몹보다 한참 크다.
 *
 * 78 이었다. 무대가 138px 이니 몸이 무대 높이의 절반을 조금 넘는 정도라,
 * **잡몹 넷이 서 있을 때와 화면 인상이 크게 다르지 않았다** — 한 마리인데
 * 특별해 보이지 않으면 우두머리전이 그냥 "적이 하나뿐인 판" 이 된다.
 *
 * 110 으로 올렸다가 **94 로 다시 내렸다.** 110 은 우두머리가 무대를 거의
 * 다 먹어서, 머리 위 말풍선과 피해 숫자가 얹힐 자리가 안 남았다 — 특수기가
 * 나갈 때 돌진까지 얹히면(`BattleView` 의 `rush`) 몸이 화면 밖으로 나갔다.
 *
 * 94 는 아군 넷(54px)의 1.7배쯤이다. 잡몹(52px)과 나란히 놓으면 확실히 크고,
 * 머리 위와 발밑에는 여유가 남는다.
 *
 * 폭 계산은 이 값을 그대로 쓰므로 (`rowWidth`·`closeInFor`) 여기만 고치면
 * 붙어 싸우는 거리와 아군 줄 자리가 같이 따라온다.
 */
export const BOSS_W = px(94);

/** 좌우 벽에서 띄우는 여백 */
export const EDGE = px(18);

/**
 * 깊이선 개수.
 *
 * **0 이다 — 안 그린다.**
 *
 * 배경이 없던 시절에는 이 선들이 유일한 바닥이었다. 지금은 뒤에 지평선이 붙은
 * 풍경이 깔리고(`BattleView` 의 bg_chapter) 그 아래가 곧 땅이라, 선까지 그으면
 * 땅 위에 격자가 얹힌 것으로 보인다 — 평면을 만들려던 것이 무늬가 된다.
 *
 * 지우는 대신 **자리는 남겨 둔다** (`GROUND_H`). 인물이 서는 높이도, 배경이
 * 끝나는 지점도 전부 이 두께에서 나오므로, 두께가 사라지면 배치가 통째로
 * 무너진다. 값만 0 으로 두면 언제든 다시 켤 수 있다.
 */
const LINES = 0;

/** 맨 뒤(지평선) 폭이 앞의 몇 배인가 — 작을수록 소실점이 가깝다 */
const BACK_W = 0.62;

/** `t` (0=앞, 1=뒤) 에서의 바닥선 높이·폭·진하기 */
const lineAt = (t: number) => ({
  /* 뒤로 갈수록 촘촘해진다. 선형이면 등간격이라 줄무늬가 된다 */
  y: GROUND_H * (1 - Math.pow(1 - t, 1.7)),
  w: 1 - (1 - BACK_W) * t,
  alpha: 0.42 - 0.28 * t,
});

export function Ground({ width }: { width: number }) {
  /* 빗변 길이·각도는 무대 폭을 알아야 나온다. 아직 모르면 가로선만 그린다 */
  const dx = width > 0 ? (width * (1 - BACK_W)) / 2 : 0;
  const edgeLen = Math.sqrt(dx * dx + GROUND_H * GROUND_H);
  const edgeDeg = (Math.atan2(GROUND_H, Math.max(1, dx)) * 180) / Math.PI;

  return (
    <View
      pointerEvents="none"
      style={{ position: 'absolute', left: 0, right: 0, bottom: 0, height: GROUND_H }}
    >
      {Array.from({ length: LINES }, (_, i) => {
        const { y, w, alpha } = lineAt(i / (LINES - 1));
        return (
          <View
            key={i}
            style={{
              position: 'absolute',
              bottom: y,
              /* 가운데를 기준으로 좁힌다 — 한쪽만 좁히면 평면이 기울어 보인다 */
              left: `${((1 - w) / 2) * 100}%`,
              right: `${((1 - w) / 2) * 100}%`,
              height: 1,
              backgroundColor: `rgba(255,255,255,${alpha})`,
            }}
          />
        );
      })}

      {/*
        좌우 빗변.

        가로선만 있으면 "겹쳐 놓은 선들" 로 보인다. 양옆을 이어 줘야 하나의
        면으로 닫힌다. 막대 하나를 눕혀서 회전시킨다 — 회전축이 가운데라
        선분의 **중점**에 놓고 돌린다.
      */}
      {/* 가로선을 끄면 빗변도 같이 꺼진다 — 양옆만 남으면 괄호 두 짝이 된다 */}
      {LINES > 0 && dx > 0 && ([-1, 1] as const).map((side) => (
        <View
          key={side}
          style={{
            position: 'absolute',
            width: edgeLen,
            height: 1,
            backgroundColor: 'rgba(255,255,255,0.3)',
            bottom: GROUND_H / 2,
            [side < 0 ? 'left' : 'right']: dx / 2 - edgeLen / 2,
            /* 왼쪽 빗변은 오른쪽 위로, 오른쪽 빗변은 왼쪽 위로 */
            transform: [{ rotate: `${side * -edgeDeg}deg` }],
          }}
        />
      ))}
    </View>
  );
}

/**
 * 이 깊이에 선 사람의 바닥 높이와 크기.
 *
 * 쿼터뷰에서 뒤에 선 사람은 **위로 올라가고 작아진다.** 둘 중 하나만 하면
 * 어색하다 — 위로만 올리면 공중에 뜬 것 같고, 작게만 하면 같은 자리에 선
 * 작은 사람이 된다.
 *
 * @param back 0 이 맨 앞
 */
/**
 * 자리 하나만큼의 높이(px) — **한 칸**.
 *
 * 1·2·3·4번 자리는 이만큼씩 위로 물러난다. 바닥에서 얼마나 띄울지도 이 값을
 * 단위로 잡는다 (`BattleView` 의 `FLOOR`) — 자리 간격과 다른 단위를 쓰면
 * "한 칸 내려 달라" 같은 말이 화면에서 한 칸이 아니게 된다.
 *
 * 7 이었다. 바닥판을 넓히면서(`GROUND_H`) 같이 올렸다 — 띠만 넓히고 간격을
 * 그대로 두면 넷이 여전히 붙어 선 채로 그 아래 빈 땅만 넓어진다. "분산되어
 * 보이게" 하는 것은 띠의 넓이가 아니라 **자리 사이의 거리**다.
 */
export const DEPTH_LIFT = 11;

export function depthAt(back: number) {
  return {
    /** 바닥선에서 띄우는 높이 */
    lift: back * DEPTH_LIFT,
    /** 크기 배수 */
    scale: 1 - back * 0.08,
  };
}

/**
 * 머리 위 한 줄이 **옆으로 얼마나 비켜설까** — 나란히 선 둘만 갈라선다.
 *
 * ## 여태 세 번 틀렸다
 *
 * 파티 전체에 걸리는 버프는 넷에게 **같은 글이 한꺼번에** 뜬다. 한글은
 * 전각이라 여덟 자면 82px 인데 (`치명타 확률 증가`) 나란히 선 두 사람이
 * 가로로 61px 밖에 안 떨어져 있어서, 그대로 두면 두 글이 맞붙어 읽을 수
 * 없는 덩어리가 된다.
 *
 * **첫 번째** — 자리마다 층을 못 박아 위로 올렸다 (가로 순서의 홀짝 × 28px).
 * 겹침은 풀렸는데 둘째 층에 걸린 사람은 옆이 텅 비어 있을 때도 **늘** 그만큼
 * 떠 있었다.
 *
 * **두 번째** — 뜨는 순간에 등록부를 뒤져 비어 있는 자리를 받게 했다. 높이는
 * 잡혔는데 이번엔 **한쪽만 움직였다**: 먼저 뜨는 쪽은 옆에 누가 올지 모른 채로
 * 가운데를 차지하고, 나중 사람이 혼자 29px 을 물러난다. 화면에서는 그게
 * "한 명만 오른쪽으로 치우쳐 뜬다" 로 보인다.
 *
 * ## 미리, 그리고 **둘 다** 비킨다
 *
 * 누가 누구와 부딪히는지는 **대형이 정해지는 순간 이미 다 안다.** 자리는
 * 대형이 못 박고 (`core/party` 의 `FORMATIONS`), 무대는 뒤로 갈수록 24px 씩
 * 올라가 서므로 (`Ground` 의 `DEPTH_LIFT`) 부딪히는 것은 **같은 가로줄에
 * 앞뒤로 선 둘**뿐이다. 뜰 때 물어볼 것이 없다.
 *
 * 미리 셈하면 짝이 **서로 반대쪽으로 반씩** 물러날 수 있다. 한쪽만 29px 을
 * 가는 대신 둘이 15px 씩 가고, 벌어지는 사이는 같은 91px 이다 — 치우쳐
 * 보이는 것은 절반이 되고, 그마저 짝을 이룬 둘이 대칭이라 "갈라섰다" 로
 * 읽힌다.
 *
 * **세 번째** — 그래도 "앞라인 가운데 있는 애만 오른쪽으로 치우쳐 뜬다" 는
 * 말이 나왔다. 대칭으로 갈라서게 해 놨는데도 그렇게 보이는 이유는, **비킬
 * 이유가 없는 글까지 비켰기** 때문이다. 나란히 선 둘은 61px 떨어져 있으므로
 * 그보다 좁은 글은 애초에 안 물린다 — 그런데 판이 열릴 때 뜨는 것이
 * 하필 다 짧은 글이다 (`공격력 증가` 50px · `지속 회복` 41px). 짝 중 하나는
 * 대개 뒤쪽 무리에 섞여 있어 안 보이고, 앞에 혼자 선 쪽만 이유 없이
 * 옆으로 밀린 것으로 보인다.
 *
 * 그래서 **길이를 본다** (`noteNeedsRoom`). 여기서 정하는 것은 방향뿐이고,
 * 실제로 비킬지는 뜨는 글자를 아는 쪽이 정한다 (`HitFx` 의 `StatusNote`).
 * 지금 표에서 실제로 비키는 것은 열아홉 중 둘뿐이다.
 *
 * 셋 이상이 한 점에 겹치는 대형은 없다. 생기면 가운데 선 사람은 좌우 표가
 * 상쇄되어 제자리에 남고 양쪽이 갈라선다 — 그게 맞는 답이다.
 */

/**
 * 부딪히는 둘이 **한쪽으로 얼마나** 비키나 (px).
 *
 * 둘이 반대쪽으로 가므로 사이는 이 값의 두 배만큼 벌어진다. 61 + 30 = 91 이
 * `NEED` 를 넘긴다.
 *
 * 더 밀 수도 있지만 그러면 글이 **제 주인에게서 멀어진다.** 15px 은 76px 짜리
 * 인물 폭의 5분의 1이라 아직 그 사람 머리 위다.
 */
export const NOTE_SHIFT = 15;

/**
 * 두 글의 한가운데가 **이만큼은 떨어져야** 안 물린다 (px).
 *
 * 제일 긴 글이 82px 이다 (`core/status` 의 `STATUS_WHAT` — `치명타 확률
 * 증가`, 9px 전각 여덟 자). 90 이면 그 둘도 갈라서고, 흔한 다섯 자짜리
 * (50px)는 넉넉하다.
 *
 * 가까움을 재는 자도 이 값이다 — 이만큼 안 떨어져 있으면 비켜야 하는
 * 사이라는 뜻이므로, 둘을 다른 숫자로 두면 "부딪히는데 안 비키는" 틈이 생긴다.
 */
const NEED = 90;

/**
 * 이 글이 화면에서 **몇 px 쯤 되나** (9px 기준).
 *
 * 한글은 한 자가 글자 크기만 하고 (전각), 사이 띄우기는 그 절반쯤이다.
 * 정확히 재려면 그려 봐야 하지만 (`onTextLayout`), 그건 이미 뜬 뒤라
 * 그때 자리를 옮기면 글이 한 프레임 뛴다. 어림으로 충분하다 — 여기서
 * 가르는 것은 "옆과 물리나 안 물리나" 하나뿐이다.
 */
function widthOf(text: string): number {
  let w = 0;
  for (const ch of text) w += ch === ' ' ? 4.5 : 9;
  return w;
}

/**
 * 이만큼보다 **넓은 글만** 비켜선다 (px).
 *
 * ## 왜 길이를 보나
 *
 * 나란히 선 둘은 61px 떨어져 있다. 그보다 좁은 글은 애초에 안 물리므로
 * 비킬 이유가 없는데, 여태 **길이와 상관없이** 비켰다 — 그래서 판이 열릴
 * 때마다 `공격력 증가`(50px)·`지속 회복`(41px) 같은 짧은 글까지 옆으로
 * 밀렸고, 그게 "앞라인 가운데 있는 애만 오른쪽으로 치우쳐 뜬다" 였다.
 *
 * 실제로 물리는 것은 지금 표에서 둘뿐이다 (`core/status` 의 `STATUS_WHAT`) —
 * `치명타 확률 증가`(72px)와 `감전 — 행동 불가`(77px). 나머지는 전부 이
 * 값 아래라 제자리에 가운데로 뜬다.
 *
 * 64 다. 61(자리 사이)보다 조금 크게 둔다 — 딱 61 로 자르면 63px 짜리
 * (`화상 지속 피해`)가 2px 물리자고 넷을 다 옮긴다.
 */
const NOTE_ROOM = 64;

/** 이 글이 옆 사람 것과 물릴 만큼 넓은가 — 아니면 비킬 이유가 없다 */
export const noteNeedsRoom = (text: string): boolean => widthOf(text) > NOTE_ROOM;

/** 자리 하나 — 가로로 어디에, 몇 번째 가로줄에 */
export interface NoteSeat {
  /** 아군 구역 왼쪽 끝에서 몇 px (`BattleView` 의 `allyXOf`) */
  x: number;
  /**
   * 몇 번째 가로줄인가 (`core/party` 의 `FormSpot.lane`).
   *
   * **세로 거리를 이걸로 가른다.** 줄이 다르면 24px 씩 어긋나 서고
   * (`Ground` 의 `DEPTH_LIFT`) 한 사람이 쓰는 높이가 23px 이라, 줄만 달라도
   * 애초에 안 겹친다. px 로 재도 되지만 줄 번호가 더 정확하고 싸다.
   */
  lane: number;
}

/**
 * 자리마다 **옆으로 얼마나 비킬까** — 넘긴 차례 그대로 돌려준다.
 *
 * 아무와도 안 부딪히면 0 이다 (대부분이 그렇다). 부딪히는 짝은 서로 반대쪽
 * 으로 `NOTE_SHIFT` 씩 간다.
 *
 * **여기서 정하는 것은 방향뿐이다.** 실제로 비킬지는 글이 그만큼 넓을 때만
 * 이고 (`noteNeedsRoom`), 그건 뜨는 글자를 아는 쪽이 판단한다
 * (`HitFx` 의 `StatusNote`).
 *
 * 순수 함수다 — 같은 대형이면 늘 같은 답이라, 화면이 언제 다시 그려지든
 * 글이 자리를 옮기지 않는다.
 */
export function noteShiftsOf(seats: readonly NoteSeat[]): number[] {
  return seats.map((me, i) => {
    /*
      같은 줄에 서 있고 가까운 사람들을 견준다. 내가 그들보다 왼쪽이면
      왼쪽으로(-1), 오른쪽이면 오른쪽으로(+1) 한 표씩 쌓는다.

      지금 대형에서는 짝이 늘 하나라 표가 하나뿐이다.
    */
    let side = 0;
    for (let j = 0; j < seats.length; j += 1) {
      if (j === i) continue;
      const o = seats[j];
      if (o.lane !== me.lane) continue;
      if (Math.abs(o.x - me.x) >= NEED) continue;
      side += me.x < o.x ? -1 : 1;
    }
    return Math.sign(side) * NOTE_SHIFT;
  });
}

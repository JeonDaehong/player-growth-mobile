/**
 * 머리 위 한 줄이 **몇 층에 뜰까** — 옆 사람과 겹칠 때만 올라간다.
 *
 * ## 여태 자리마다 층이 못 박혀 있었다
 *
 * 파티 전체에 걸리는 버프는 넷에게 **같은 글이 한꺼번에** 뜬다. 한글은
 * 전각이라 다섯 자면 45px 인데 나란히 선 두 사람이 가로로 43px 밖에 안
 * 떨어져 있어서 (`BattleView` 의 `formLayout`), 같은 높이에 뜨면 두 글이
 * 맞붙어 읽을 수 없는 덩어리가 된다.
 *
 * 그래서 **가로로 센 순서의 홀짝**으로 두 층을 번갈아 썼다 (`noteLiftOf`).
 * 겹침은 풀렸는데 대가가 컸다 — 둘째 층에 걸린 사람은 **언제나** 28px 을 더
 * 올라간다. 혼자 디버프 하나 걸렸을 때도, 옆 사람 머리 위가 텅 비어 있을
 * 때도. 화면에 줄이 하나뿐인 순간에도 그 하나가 머리에서 한참 떠 있었다.
 *
 * ## 겹칠 때만 올린다
 *
 * 층은 **지금 실제로 옆에 글이 떠 있을 때만** 올라가야 한다. 그건 자리
 * 번호로는 알 수 없다 — 누가 언제 뜨는지는 그리는 순간에 정해지기 때문이다.
 *
 * 그래서 뜨는 쪽이 **그 순간에 물어본다.** 가까이 있는 다른 사람이 이미 쓰고
 * 있는 층을 빼고 제일 낮은 층을 받는다. 아무도 없으면 0 층 — 머리 바로 위다.
 *
 * ## 왜 모듈 하나에 두나
 *
 * 인물은 저마다 딴 컴포넌트다 (`Fighter` 넷 · 적 열). 리액트 상태로 나누면
 * 한 명이 글을 띄울 때마다 나머지가 전부 다시 그려지는데, 그 자리는 인물과
 * 이펙트가 매 프레임 도는 전투 화면이다. 여기는 **그리기에 아무 영향이 없는**
 * 값이라 (뜨는 그 순간 한 번 정해지고 안 바뀐다) 바깥에 두는 것이 맞다.
 *
 * 세션 하나에서만 산다 — 판이 끝나면 시간이 지나 저절로 비워진다.
 */

/**
 * 한 층이 얼마나 높은가 (px).
 *
 * **한 사람이 쓰는 높이보다 커야 한다.** 한꺼번에 두 줄까지 쌓이고
 * (`HitFx` 의 `MarkNotes` — `slice(-2)`) 줄 간격이 12px, 9px 글자가 11px
 * 이라 한 덩어리가 23px 이다. 28 이면 그 위로 5px 이 남는다.
 *
 * 여기가 여태 세 번 틀린 자리다 — 15 · 26 · 46 이었는데 앞의 둘은 한 사람
 * 몫보다 작아서 옆 사람 줄 사이에 끼어들었고 (여섯 줄이 한 덩어리로
 * 보였다), 46 은 석 줄까지 허용하던 시절의 값이라 지금은 너무 높다.
 */
export const NOTE_TIER = 28;

/**
 * 몇 px 안에 있으면 **겹치는 것으로 보나**.
 *
 * 글은 인물 한가운데에 뜨고 다섯 자면 45px 쯤이다 (9px 전각). 두 글의
 * 한가운데가 이만큼 안에 있으면 서로 물린다.
 *
 * 파티는 나란히 선 둘이 43px 이라 늘 걸리고 (그래서 층이 필요하다), 앞뒤로
 * 물러선 둘은 130px 쯤이라 안 걸린다.
 */
const NEAR = 62;

/** 층은 셋까지 — 그 위로는 인물 키만큼 떠서, 겹치는 편이 낫다 */
const LANES = 3;

/** 아군끼리, 적끼리만 견준다 — 두 구역의 좌표가 서로 다른 자를 쓴다 */
export type NoteZone = 'ally' | 'foe';

interface Held {
  zone: NoteZone;
  x: number;
  lane: number;
  /** 이 시각이 지나면 없는 것으로 본다 (ms, `Date.now()` 기준) */
  till: number;
}

const held = new Map<string, Held>();

/**
 * 이 사람의 머리 위 글이 **몇 층에 뜰까** (0 이 머리 바로 위).
 *
 * ## 이미 떠 있으면 그 층을 그대로 쓴다
 *
 * 한 사람에게 두 가지가 잇따라 걸리면 이 함수가 두 번 불린다. 그때 층이
 * 바뀌면 먼저 뜬 줄과 나중에 뜬 줄이 서로 다른 높이에 떠서, 한 사람의 두
 * 줄이 두 사람 것처럼 보인다. 아직 살아 있는 동안은 같은 층을 돌려주고
 * 시간만 늘린다.
 *
 * @param who  누구인가 — 구역 안에서 겹치지 않는 이름이면 된다
 * @param zone 아군인가 적인가. 두 구역은 서로 안 견준다
 * @param x    그 사람이 가로로 어디 서 있나 (같은 구역 안에서 같은 자로 잰 값)
 * @param ms   이 글이 얼마나 떠 있나
 */
export function claimNoteLane(
  who: string, zone: NoteZone, x: number, ms: number,
): number {
  const now = Date.now();
  /* 지난 것부터 걷는다 — 안 걷으면 죽은 자리가 층을 영영 잡고 있다 */
  for (const [k, v] of held) if (v.till <= now) held.delete(k);

  const mine = held.get(who);
  if (mine) {
    mine.x = x;
    mine.till = now + ms;
    return mine.lane;
  }

  /* 가까이 있는 남들이 쓰고 있는 층 */
  const taken = new Set<number>();
  for (const [k, v] of held) {
    if (k === who || v.zone !== zone) continue;
    if (Math.abs(v.x - x) < NEAR) taken.add(v.lane);
  }
  let lane = 0;
  while (lane < LANES && taken.has(lane)) lane += 1;
  /* 셋이 다 찼으면 제일 낮은 데로 돌아간다 — 겹치는 편이 하늘에 뜨는 것보다 낫다 */
  if (lane >= LANES) lane = 0;

  held.set(who, { zone, x, lane, till: now + ms });
  return lane;
}

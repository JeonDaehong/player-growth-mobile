/**
 * 머리 위 한 줄이 **어디에 뜰까** — 옆 사람과 부딪힐 때만 비켜선다.
 *
 * ## 여태 자리마다 층이 못 박혀 있었다
 *
 * 파티 전체에 걸리는 버프는 넷에게 **같은 글이 한꺼번에** 뜬다. 한글은
 * 전각이라 여덟 자면 82px 인데 (`치명타 확률 증가`) 나란히 선 두 사람이
 * 가로로 61px 밖에 안 떨어져 있어서, 같은 자리에 뜨면 두 글이 맞붙어 읽을
 * 수 없는 덩어리가 된다.
 *
 * 그래서 **가로로 센 순서의 홀짝**으로 두 층을 번갈아 썼다. 겹침은 풀렸는데
 * 대가가 컸다 — 둘째 층에 걸린 사람은 **언제나** 28px 을 더 올라간다. 혼자
 * 디버프 하나 걸렸을 때도, 옆 사람 머리 위가 텅 비어 있을 때도.
 *
 * ## 위로 비키지 말고 **옆으로** 비킨다
 *
 * 한 번은 "겹칠 때만 위로 올린다" 로 고쳤는데 그래도 모자랐다. 부딪히는지를
 * **가로 거리만으로** 봤기 때문이다 — 무대는 쿼터뷰라 뒷줄이 24px 씩 위로
 * 올라가 서는데 (`Ground` 의 `DEPTH_LIFT`), 위아래로 한참 떨어진 둘이
 * 가로로 가깝다는 이유로 서로 층을 뺏었다. 넷이 한꺼번에 말하면 마지막
 * 사람이 3층(56px)까지 밀렸다.
 *
 * 둘을 고친다.
 *
 *   **부딪힘을 가로·세로 둘로 본다** — 위아래로 벌어진 둘은 애초에 안 부딪힌다.
 *   그러면 세 대형 어디서나 실제로 부딪히는 짝은 **하나뿐**이다 (같은 가로줄에
 *   앞뒤로 선 둘 — `2-2` 는 그런 짝이 둘)
 *
 *   **비키는 방향이 위가 아니라 옆이다** — 부딪히는 둘 중 나중 사람이
 *   반대쪽으로, **모자란 만큼만** 물러난다 (`NEED`). 61px 이던 사이가
 *   90px 이 되어 82px 짜리 긴 글도 안 맞붙고, **둘 다 제 머리 위에 남는다.**
 *
 * 층은 그래도 남겨 둔다 — 같은 쪽으로 물러날 데가 없는 셋 이상이 몰릴 때
 * 쓰는 마지막 수단이다 (지금 파티에서는 안 일어난다).
 *
 * ## 왜 모듈 하나에 두나
 *
 * 인물은 저마다 딴 컴포넌트다 (`Fighter` 넷 · 적 열). 리액트 상태로 나누면
 * 한 명이 글을 띄울 때마다 나머지가 전부 다시 그려지는데, 그 자리는 인물과
 * 이펙트가 매 프레임 도는 전투 화면이다. 여기는 **그리기에 아무 영향이 없는**
 * 값이라 (뜨는 그 순간 한 번 정해지고 안 바뀐다) 바깥에 두는 것이 맞다.
 *
 * 세션 하나에서만 산다 — 판이 끝나면 시간이 지나 저절로 비워진다.
 */

/**
 * 한 층이 얼마나 높은가 (px).
 *
 * **한 사람이 쓰는 높이보다 커야 한다.** 한꺼번에 두 줄까지 쌓이고
 * (`HitFx` 의 `MarkNotes` — `slice(-2)`) 줄 간격이 12px, 9px 글자가 11px
 * 이라 한 덩어리가 23px 이다. 28 이면 그 위로 5px 이 남는다.
 *
 * 이제 거의 안 쓰인다 — 부딪히는 짝은 옆으로 비키므로 (`NOTE_SHIFT`) 여기까지
 * 오는 것은 셋 이상이 한 점에 몰릴 때뿐이다.
 */
export const NOTE_TIER = 28;

/**
 * 옆으로 **최대** 얼마나 비키나 (px).
 *
 * 실제로 비키는 만큼은 그때그때 다르다 — 벌써 얼마나 떨어져 있는지, 상대가
 * 이미 물러났는지에 따라 필요한 만큼만 간다 (`claimNoteSpot`).
 *
 * 상한이 있는 이유는 글이 **제 주인에게서 멀어지면 안 되기** 때문이다.
 * 30px 은 76px 짜리 인물의 어깨쯤이라 "이 사람 것" 이 아직 안 흔들린다.
 * 그 위로 가면 두 사람 사이에 떠 있는 글이 된다.
 */
export const NOTE_SHIFT = 30;

/**
 * 두 글의 한가운데가 **이만큼은 떨어져야** 안 물린다 (px).
 *
 * 제일 긴 글이 82px 이다 (`core/status` 의 `STATUS_WHAT` — `치명타 확률
 * 증가`, 9px 전각 여덟 자). 90 이면 그 둘도 8px 을 남기고 갈라서고, 흔한
 * 다섯 자짜리(50px)는 넉넉하다.
 *
 * 가까움을 재는 자도 이 값이다 — 이만큼 안 떨어져 있으면 곧 비켜야 하는
 * 사이라는 뜻이므로, 둘을 다른 숫자로 두면 "부딪히는데 안 비키는" 틈이 생긴다.
 */
const NEED = 90;
const NEAR_X = NEED;

/**
 * 세로로 몇 px 안에 있어야 **부딪히는 것으로 보나**.
 *
 * 여기가 없어서 위의 이야기가 났다. 무대는 뒤로 갈수록 24px 씩 올라가 서므로
 * (`Ground` 의 `DEPTH_LIFT`) 가로줄이 다르면 글도 그만큼 어긋나 뜬다 — 한
 * 사람이 쓰는 높이가 23px 이니 24px 벌어진 둘은 애초에 안 겹친다.
 *
 * 20 이다. 같은 가로줄(0)만 걸리고 한 줄 차이(24)부터는 안 걸린다.
 */
const NEAR_Y = 20;

/** 층은 셋까지 — 그 위로는 인물 키만큼 떠서, 겹치는 편이 낫다 */
const LANES = 3;

/** 아군끼리, 적끼리만 견준다 — 두 구역의 좌표가 서로 다른 자를 쓴다 */
export type NoteZone = 'ally' | 'foe';

/** 이 사람의 글이 어디에 뜨나 */
export interface NoteSpot {
  /** 몇 층인가 — 0 이 머리 바로 위 */
  lane: number;
  /** 옆으로 얼마나 밀렸나 (px). 왼쪽이 음수 */
  shift: number;
}

/** 아무와도 안 부딪힌다 — 머리 바로 위, 가운데 */
const HOME: NoteSpot = { lane: 0, shift: 0 };

interface Held extends NoteSpot {
  zone: NoteZone;
  x: number;
  y: number;
  /** 이 시각이 지나면 없는 것으로 본다 (ms, `Date.now()` 기준) */
  till: number;
}

const held = new Map<string, Held>();

/**
 * 이 사람의 머리 위 글이 **어디에 뜰까**.
 *
 * ## 이미 떠 있으면 그 자리를 그대로 쓴다
 *
 * 한 사람에게 두 가지가 잇따라 걸리면 이 함수가 두 번 불린다. 그때 자리가
 * 바뀌면 먼저 뜬 줄과 나중에 뜬 줄이 서로 다른 데 떠서, 한 사람의 두 줄이
 * 두 사람 것처럼 보인다. 아직 살아 있는 동안은 같은 자리를 돌려주고 시간만
 * 늘린다.
 *
 * @param who  누구인가 — 구역 안에서 겹치지 않는 이름이면 된다
 * @param zone 아군인가 적인가. 두 구역은 서로 안 견준다
 * @param x    가로로 어디 서 있나 (같은 구역 안에서 같은 자로 잰 값)
 * @param y    세로로 얼마나 올라가 서 있나 (`Ground` 의 `depthAt` 의 `lift`)
 * @param ms   이 글이 얼마나 떠 있나
 */
export function claimNoteSpot(
  who: string, zone: NoteZone, x: number, y: number, ms: number,
): NoteSpot {
  const now = Date.now();
  /* 지난 것부터 걷는다 — 안 걷으면 죽은 자리가 자리를 영영 잡고 있다 */
  for (const [k, v] of held) if (v.till <= now) held.delete(k);

  const mine = held.get(who);
  if (mine) {
    mine.x = x;
    mine.y = y;
    mine.till = now + ms;
    return { lane: mine.lane, shift: mine.shift };
  }

  /* 지금 실제로 부딪히는 사람들 — 가로로 가깝고 세로로도 같은 줄 */
  const near: Held[] = [];
  for (const [k, v] of held) {
    if (k === who || v.zone !== zone) continue;
    if (Math.abs(v.x - x) < NEAR_X && Math.abs(v.y - y) < NEAR_Y) near.push(v);
  }

  if (!near.length) {
    held.set(who, { ...HOME, zone, x, y, till: now + ms });
    return HOME;
  }

  /*
    ── 제일 가까운 쪽의 **반대편으로, 필요한 만큼만** 물러난다 ──

    ## 왜 정해진 거리가 아닌가

    둘이 사이좋게 반씩 물러나면 좋겠지만 그럴 수가 없다. 먼저 뜨는 쪽은
    **자기 옆에 누가 올지 모른 채로** 자리를 정하기 때문이다 (그 순간에는
    등록부가 비어 있다). 그래서 늘 나중 사람만 비키게 되고, 정해진 거리로
    비키면 앞사람이 안 물러난 만큼 모자란다.

    그래서 **지금 실제로 얼마나 떨어져 있는지**를 재서 모자란 만큼만 간다.
    앞사람이 가만히 있으면 내가 두 몫을 가고, 앞사람이 이미 반대쪽으로
    물러났으면 나는 조금만 가면 된다. 어느 쪽이든 결과는 `NEED` 다.

    상한(`NOTE_SHIFT`)에 걸리면 거기서 멈춘다 — 더 가면 글이 제 주인에게서
    떨어져 나온다. 그때는 `NEED` 를 다 못 채우지만, 그래도 안 비키는 것보다
    낫다.
  */
  const nearest = near.reduce(
    (a, v) => (Math.abs(v.x - x) < Math.abs(a.x - x) ? v : a),
  );
  /* 상대는 이미 비켜 있을 수 있다 — 그 자리를 기준으로 잰다 */
  const at = nearest.x + nearest.shift;
  const dir = x < at ? -1 : 1;
  const shift = dir * Math.min(NOTE_SHIFT, Math.max(0, NEED - Math.abs(x - at)));

  /*
    ── 같은 쪽으로 물러난 사람하고만 층을 다툰다 ──

    반대쪽으로 간 사람과는 이미 `NEED` 만큼 벌어졌으므로 같은 층을 써도 된다.
    이 갈래를 안 두면 짝을 이룬 둘이 서로 비켰는데도 한 명이 괜히 위로
    올라간다 — 지금 파티에서 층이 안 쓰이는 이유가 이 줄이다.

    **거리가 아니라 방향으로 견준다.** 비키는 거리는 그때그때 다른 숫자라
    (`NEED - 지금 사이`) 같은 쪽으로 갔는데도 값이 안 맞을 수 있다.
  */
  const side = Math.sign(shift);
  const taken = new Set(
    near.filter((v) => Math.sign(v.shift) === side).map((v) => v.lane),
  );
  let lane = 0;
  while (lane < LANES && taken.has(lane)) lane += 1;
  /* 셋이 다 찼으면 제일 낮은 데로 돌아간다 — 겹치는 편이 하늘에 뜨는 것보다 낫다 */
  if (lane >= LANES) lane = 0;

  const spot: NoteSpot = { lane, shift };
  held.set(who, { ...spot, zone, x, y, till: now + ms });
  return spot;
}
